"""
CrisisState — Shared type contract for the LangGraph agent swarm.

This TypedDict defines the full state object passed between all 6 agents.
Fields are populated progressively as agents execute in sequence.

Phase 3 will implement the full LangGraph state machine using this schema.
"""
from typing import TypedDict, Optional, List, Dict, Any, Annotated

def merge_messages(left: list, right: list) -> list:
    """Reducer to merge message lists from parallel agent nodes without duplicate entries."""
    if not left:
        return right or []
    if not right:
        return left or []
    merged = list(left)
    for item in right:
        if item not in merged:
            merged.append(item)
    return merged


class AgentFinding(TypedDict):
    """Single agent's contribution to the crisis evidence chain."""
    agent: str                  # Agent name
    confidence: float           # 0.0 - 1.0
    summary: str                # Human-readable finding
    data: Dict[str, Any]        # Raw evidence payload
    timestamp: str              # ISO 8601


class RouteRecommendation(TypedDict):
    """Alternative route generated by RouteOptimizationAgent."""
    description: str
    waypoints: List[Dict[str, float]]   # [{lat, lon}, ...]
    distance_km: float
    eta_minutes: int
    fuel_increase_pct: float
    risk_score: float                   # 0.0 - 1.0


class NormalizedEvent(TypedDict):
    source: str         # 'bmkg', 'tomtom', 'aisstream', 'nasa_firms', 'osint'
    event_type: str     # 'flood', 'congestion', 'port_closure', 'fire', 'price_spike'
    severity: str       # 'low', 'medium', 'high', 'critical'
    raw_payload: Dict[str, Any]
    validated: bool
    validation_errors: List[str]


class LTMEpisode(TypedDict):
    episode_id: str
    title: str
    description: str
    crisis_type: str
    inflation_multiplier: float
    recovery_days: int
    similarity_score: float


class GraphRAGNode(TypedDict):
    entity_id: str
    entity_type: str    # 'port', 'route', 'warehouse', 'commodity', 'supplier'
    name: str
    relation: str       # 'DEPENDS_ON', 'SHIPS_VIA', 'SUPPLIES', 'LOCATED_IN'
    impact_score: float


class CrisisState(TypedDict):
    """
    The central state object shared across all LangGraph agents.
    Stored in Redis KV (STM) for the duration of an active crisis.
    """
    # Crisis identification
    crisis_id: str
    title: str
    type: str                           # 'flood', 'port_closure', 'wildfire', 'congestion', 'earthquake'
    is_simulated: bool                  # True if triggered via TheoTown simulation

    # Input event parameters to prevent filtering
    source: Optional[str]
    severity: Optional[str]
    event_type: Optional[str]

    # Location
    lat: float
    lon: float
    region: str                         # 'north_sumatra', 'java', etc.
    affected_polygon: Optional[List]    # GeoJSON polygon coordinates

    # Operational decision (OD) inputs.
    # LangGraph 0.2.28 only carries keys declared on the state schema, so these
    # must stay listed here or a dashboard selection is silently dropped before
    # the RouteOptimizationAgent runs. camelCase aliases are declared because the
    # dashboard payload historically used them; data_collection normalizes both
    # spellings onto the canonical snake_case channels.
    origin: Optional[Any]                # node id / name / [lon, lat]
    destination: Optional[Any]           # node id / name / [lon, lat]
    start_location: Optional[Any]        # legacy alias for origin
    end_location: Optional[Any]          # legacy alias for destination
    origin_coords: Optional[List[float]]  # [lon, lat]
    dest_coords: Optional[List[float]]    # [lon, lat]
    commodity: Optional[str]
    cargo_tonnage: Optional[float]
    cargoTonnage: Optional[float]        # camelCase alias (dashboard payload)
    has_bkhit_cert: Optional[bool]
    hasBkhitCert: Optional[bool]         # camelCase alias (dashboard payload)
    vehicle_gross_weight_ton: Optional[float]
    vehicleGrossWeightTon: Optional[float]  # camelCase alias (dashboard payload)
    modality: Optional[str]              # 'truck' | 'maritime' | 'air' | 'multimodal'
    radius_km: Optional[float]

    # Status tracking
    status: str                         # 'detecting', 'validating', 'validated', 'resolved'
    overall_confidence: float           # 0.0 - 1.0 (gate fires at 0.85)

    # Agent findings (populated as each agent runs)
    data_collection_finding: Optional[AgentFinding]
    osint_hazard_finding: Optional[AgentFinding]
    prediction_finding: Optional[AgentFinding]
    route_optimization_finding: Optional[AgentFinding]
    economic_intelligence_finding: Optional[AgentFinding]
    decision_support_output: Optional[str]  # Final synthesized summary

    # Route recommendations
    route_recommendations: List[RouteRecommendation]

    # Economic forecast
    inflation_forecast: Optional[Dict[str, Any]]   # {commodity, region, pct_increase, timeframe_hours}

    # GraphRAG traversal result
    causal_chain: Optional[List[Dict[str, str]]]   # [{node, relation, node}, ...]

    # New fields for Phase 3
    normalized_event: Optional[NormalizedEvent]
    hazard_polygons: Optional[List[Dict]]
    congestion_forecast: Optional[Dict[str, Any]]
    ltm_episodes: Optional[List[LTMEpisode]]
    graphrag_chain: Optional[List[GraphRAGNode]]
    consensus_breakdown: Optional[Dict[str, float]]
    validated: bool

    # Ingestion provenance + pre-consensus signals (Workpackage 1)
    raw_event: Optional[Dict[str, Any]]          # original adapter/UI event payload
    weather_fusion: Optional[Dict[str, Any]]     # BMKG/Open-Meteo FeatureCollection
    pre_economic_signal: Optional[Dict[str, Any]]  # fast PIHPS pre-gate anomaly

    # News Intelligence & Corridor Grounding
    verified_news_citations: Optional[List[Dict[str, Any]]]
    blocked_corridors: Optional[List[str]]
    news_affected_commodities: Optional[List[str]]

    # Operational Decision & Intermodal Solvers
    hedging_breakdown: Optional[Dict[str, Any]]
    compliance_status: Optional[Dict[str, Any]]
    chokepoint_delay_multiplier: Optional[float]

    # Validated-alert fan-out & degradation reporting (Agent 6 terminal stage)
    validated_alert: Optional[Dict[str, Any]]
    notification_status: Optional[str]       # 'sent' | 'failed' | 'degraded_log_only'
    degraded_sources: Optional[List[str]]    # e.g. ['whatsapp', 'redis_validated_alerts']

    # Metadata
    created_at: str                     # ISO 8601
    updated_at: str                     # ISO 8601
    messages: Annotated[List[str], merge_messages]                 # Agent communication log

